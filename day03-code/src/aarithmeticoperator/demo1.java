package aarithmeticoperator;

public class demo1 {
    public static void main(String[] args) {
        //+
        System.out.println(3+2);
        //-
        System.out.println(5-4);
        //*
        System.out.println(5*5);


        //如果在计算的是偶有小数参与
        //结论：
        //在代码中，如果有小数参与计算，结果有可能不精确
        //
        System.out.println(1.1+1.01);
        System.out.println(1.1-1.01);
        System.out.println(1.1*1.01);
    }
}
