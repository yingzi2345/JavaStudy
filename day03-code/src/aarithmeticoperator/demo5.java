package aarithmeticoperator;

public class demo5 {
    public static void main(String[] args) {
        //++和--,如果单独写一行是一样的。
        int a = 10;
        a++;
        System.out.println(a);
        ++a;
        System.out.println(a);
        a--;
        System.out.println(a);
        --a;
        System.out.println(a);
    }
}
